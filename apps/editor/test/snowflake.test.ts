/**
 * Snowflake export (design phase3 §6.3): a snapshot for 02-ecommerce, and for every example our
 * output re-imported with `@dbml/core`'s Snowflake importer reproduces the tables, columns, primary
 * keys and foreign keys.
 */
import { importer } from '@dbml/core';
import { compileDbml, type DiagramModel } from '@relvista/core';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { describe, expect, it } from 'vitest';
import { exportSnowflake, quoteIdent, snowflakeType } from '../src/sql/snowflake.js';
import { EXPORT_FORMATS } from '../src/sql/sql.js';
import { EXAMPLES_DIR } from './helpers.js';

function models(): Array<{ name: string; model: DiagramModel }> {
  const out: Array<{ name: string; model: DiagramModel }> = [];
  for (const n of readdirSync(EXAMPLES_DIR).sort()) {
    const p = join(EXAMPLES_DIR, n);
    const files: Record<string, string> = {};
    let entry = n;
    if (statSync(p).isDirectory()) {
      const walk = (dir: string) => {
        for (const f of readdirSync(dir)) {
          const q = join(dir, f);
          if (statSync(q).isDirectory()) walk(q);
          else if (f.endsWith('.dbml')) files[relative(p, q)] = readFileSync(q, 'utf8');
        }
      };
      walk(p);
      entry = 'main.dbml';
    } else if (n.endsWith('.dbml')) files[n] = readFileSync(p, 'utf8');
    else continue;
    const model = compileDbml({ files, entry }).model;
    if (model) out.push({ name: n, model });
  }
  return out;
}

const key = (schema: string, name: string) => `${schema}.${name}`.toLowerCase();

function shape(model: DiagramModel) {
  const byId = new Map(model.tables.map((t) => [t.id, t]));
  const tables = model.tables.map((t) => {
    const pk = new Set(t.columns.filter((c) => c.pk).map((c) => c.name.toLowerCase()));
    for (const i of t.indexes)
      if (i.pk) for (const c of i.columns) if (c.kind === 'column') pk.add(c.value.toLowerCase());
    return {
      table: key(t.schema, t.name),
      columns: t.columns.map((c) => c.name.toLowerCase()),
      pk: [...pk].sort(),
    };
  });
  const fks = model.refs
    .filter((r) => r.fkSide !== null && !r.inactive)
    .map((r) => {
      const fk = r.fkSide === 'from' ? r.from : r.to;
      const pk = r.fkSide === 'from' ? r.to : r.from;
      const a = byId.get(fk.tableId)!;
      const b = byId.get(pk.tableId)!;
      return `${key(a.schema, a.name)}(${fk.columns.join(',')}) -> ${key(b.schema, b.name)}(${pk.columns.join(',')})`.toLowerCase();
    })
    .sort();
  return { tables: tables.sort((a, b) => (a.table < b.table ? -1 : 1)), fks };
}

describe('Snowflake export', () => {
  it('is listed as an export format', () => {
    expect(EXPORT_FORMATS.map((f) => f.label)).toContain('Snowflake');
  });

  it('quotes identifiers only when Snowflake needs it', () => {
    expect(quoteIdent('users')).toBe('users');
    expect(quoteIdent('User_2$')).toBe('User_2$');
    expect(quoteIdent('order')).toBe('"ORDER"');
    expect(quoteIdent('body')).toBe('"BODY"');
    expect(quoteIdent('name')).toBe('name');
    expect(quoteIdent('my col')).toBe('"my col"');
    expect(quoteIdent('2fa')).toBe('"2fa"');
    expect(quoteIdent('a"b')).toBe('"a""b"');
  });

  it('maps column types', () => {
    const t = (type: string, extra: { increment?: boolean; enumId?: string } = {}) =>
      snowflakeType({ type, enumId: extra.enumId ?? null, increment: extra.increment ?? false });
    expect(t('serial')).toBe('NUMBER AUTOINCREMENT');
    expect(t('bigserial')).toBe('NUMBER AUTOINCREMENT');
    expect(t('integer', { increment: true })).toBe('INTEGER AUTOINCREMENT');
    expect(t('varchar(255)')).toBe('VARCHAR(255)');
    expect(t('text')).toBe('VARCHAR');
    expect(t('timestamp')).toBe('TIMESTAMP_NTZ');
    expect(t('timestamptz')).toBe('TIMESTAMP_TZ');
    expect(t('timestamp with time zone')).toBe('TIMESTAMP_TZ');
    expect(t('json')).toBe('VARIANT');
    expect(t('jsonb')).toBe('VARIANT');
    expect(t('uuid')).toBe('VARCHAR(36)');
    expect(t('boolean')).toBe('BOOLEAN');
    expect(t('decimal(10, 2)')).toBe('DECIMAL(10,2)');
    expect(t('numeric')).toBe('NUMERIC');
    expect(t('text[]')).toBe('ARRAY');
    expect(t('double precision')).toBe('DOUBLE');
    expect(t('bigint unsigned')).toBe('BIGINT');
    expect(t('mood', { enumId: 'public.mood' })).toBe('VARCHAR');
    expect(t('geography')).toBe('geography');
  });

  it('writes 02-ecommerce like this', () => {
    const model = models().find((m) => m.name === '02-ecommerce.dbml')!.model;
    expect(exportSnowflake(model)).toMatchInlineSnapshot(`
      "-- storefront: Snowflake DDL generated by relvista
      -- Snowflake records PRIMARY KEY, UNIQUE and FOREIGN KEY constraints but does not enforce them
      -- (NOT NULL is enforced). It has no secondary indexes, CHECK constraints or enum types: those
      -- are kept below as comments.

      CREATE TABLE countries (
        code CHAR(2) PRIMARY KEY,
        name VARCHAR(100) NOT NULL,
        continent_name VARCHAR(50)
      );

      CREATE TABLE merchants (
        id INTEGER AUTOINCREMENT,
        country_code CHAR(2),
        merchant_name VARCHAR(120) NOT NULL,
        admin_id INTEGER,
        created_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
        PRIMARY KEY (id, country_code)
      );

      CREATE TABLE merchant_periods (
        id INTEGER AUTOINCREMENT PRIMARY KEY,
        merchant_id INTEGER NOT NULL,
        country_code CHAR(2) NOT NULL,
        start_date DATE NOT NULL,
        end_date DATE
      );

      CREATE TABLE users (
        id INTEGER AUTOINCREMENT PRIMARY KEY,
        full_name VARCHAR(200),
        email VARCHAR(255) NOT NULL UNIQUE,
        country_code CHAR(2),
        created_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
      );

      CREATE TABLE user_profiles (
        user_id INTEGER PRIMARY KEY,
        avatar_url VARCHAR(500),
        bio VARCHAR
      );

      CREATE TABLE categories (
        id INTEGER AUTOINCREMENT PRIMARY KEY,
        parent_id INTEGER,
        name VARCHAR(100) NOT NULL
      );

      CREATE TABLE products (
        id INTEGER AUTOINCREMENT PRIMARY KEY,
        name VARCHAR(200) NOT NULL,
        merchant_id INTEGER NOT NULL,
        merchant_country CHAR(2) NOT NULL,
        category_id INTEGER,
        price DECIMAL(10,2) DEFAULT 0 NOT NULL,
        status VARCHAR(20) DEFAULT 'draft',
        created_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
      );

      CREATE TABLE tags (
        id INTEGER AUTOINCREMENT PRIMARY KEY,
        label VARCHAR(50) NOT NULL UNIQUE
      );

      CREATE TABLE orders (
        id INTEGER AUTOINCREMENT PRIMARY KEY,
        user_id INTEGER NOT NULL,
        status VARCHAR(20) DEFAULT 'pending' NOT NULL,
        coupon_id INTEGER,
        created_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
      );

      CREATE TABLE order_items (
        order_id INTEGER,
        product_id INTEGER,
        quantity INTEGER DEFAULT 1 NOT NULL,
        unit_price DECIMAL(10,2) NOT NULL,
        PRIMARY KEY (order_id, product_id)
      );

      CREATE TABLE coupons (
        id INTEGER AUTOINCREMENT PRIMARY KEY,
        code VARCHAR(32) NOT NULL UNIQUE,
        percent_off INTEGER
      );

      CREATE TABLE payments (
        id INTEGER AUTOINCREMENT PRIMARY KEY,
        order_id INTEGER NOT NULL,
        amount DECIMAL(10,2) NOT NULL,
        paid_at TIMESTAMP_NTZ
      );

      CREATE TABLE admins (
        id INTEGER AUTOINCREMENT PRIMARY KEY,
        login VARCHAR(64) NOT NULL UNIQUE
      );

      ALTER TABLE merchants ADD FOREIGN KEY (country_code) REFERENCES countries (code);
      ALTER TABLE user_profiles ADD FOREIGN KEY (user_id) REFERENCES users (id);
      ALTER TABLE categories ADD FOREIGN KEY (parent_id) REFERENCES categories (id);
      ALTER TABLE merchants ADD FOREIGN KEY (admin_id) REFERENCES admins (id);
      ALTER TABLE orders ADD CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE CASCADE;
      ALTER TABLE users ADD FOREIGN KEY (country_code) REFERENCES countries (code) ON DELETE SET NULL;
      ALTER TABLE orders ADD FOREIGN KEY (coupon_id) REFERENCES coupons (id) ON DELETE SET NULL;
      ALTER TABLE order_items ADD CONSTRAINT order_lines FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE;
      ALTER TABLE order_items ADD FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT ON UPDATE NO ACTION;
      ALTER TABLE payments ADD CONSTRAINT order_payments FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE;
      ALTER TABLE products ADD FOREIGN KEY (merchant_id, merchant_country) REFERENCES merchants (id, country_code) ON DELETE CASCADE;
      ALTER TABLE merchant_periods ADD CONSTRAINT merchant_period_owner FOREIGN KEY (merchant_id, country_code) REFERENCES merchants (id, country_code);
      -- many-to-many: products (id) <> tags (id); add a junction table to enforce it
      ALTER TABLE products ADD FOREIGN KEY (category_id) REFERENCES categories (id);

      COMMENT ON COLUMN categories.parent_id IS 'Self reference; null for root categories';
      "
    `);
  });

  describe.each(models())('$name', ({ model }) => {
    it('re-imports with the same tables, columns, primary and foreign keys', () => {
      const sql = exportSnowflake(model);
      expect(sql).toContain('CREATE TABLE');
      let dbml: string;
      try {
        dbml = importer.import(sql, 'snowflake');
      } catch (e) {
        throw new Error(
          `Snowflake importer rejected the output: ${JSON.stringify(e).slice(0, 500)}\n${sql}`,
          { cause: e },
        );
      }
      const back = compileDbml(dbml).model;
      expect(back, dbml).not.toBeNull();
      expect(shape(back!)).toEqual(shape(model));
    });
  });
});
