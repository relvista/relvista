/**
 * Fonts for PDF text outside WinAnsi (docs/design/phase3-v1.md §4.4, §13). The standard PDF fonts
 * draw WinAnsi only; for other text the export embeds one of three bundled fonts, which jsPDF
 * subsets to the glyphs the document uses (Identity-H encoding with a ToUnicode map, so the text
 * stays selectable and searchable):
 *
 * - `sansRegular` / `sansBold`: Noto Sans (SIL OFL 1.1), Latin, Greek and Cyrillic;
 * - `cjk`: Noto Sans' Latin, Greek and Cyrillic plus Droid Sans Fallback's (Apache 2.0) CJK
 *   ideographs, kana and full-width forms, regular weight only.
 *
 * Each font is a module of its own (`fonts/*.ts`, generated by `scripts/pdf-fonts.py`), loaded
 * with `import()` only when a document has text that needs it. Text no font covers — Arabic and
 * Hebrew (right to left, and Arabic needs shaping), Indic scripts, Hangul, emoji, combining marks
 * left after NFC — keeps the raster fallback.
 */
import { FONT_COVERAGE } from './fonts/coverage.js';
import { isWinAnsi } from './plan.js';

/** An embeddable font. */
export type PdfFontId = keyof typeof FONT_COVERAGE;

/** jsPDF font name and style each font is registered under (and the CSS family svg2pdf sees). */
export const PDF_FONTS: Readonly<
  Record<PdfFontId, { family: string; style: 'normal' | 'bold'; weight: number }>
> = {
  sansRegular: { family: 'rvpdfsans', style: 'normal', weight: 400 },
  sansBold: { family: 'rvpdfsans', style: 'bold', weight: 700 },
  cjk: { family: 'rvpdfcjk', style: 'normal', weight: 400 },
};

function inRanges(ranges: readonly number[], cp: number): boolean {
  // Flat [first, last, first, last, …], sorted: binary search over the pairs.
  let lo = 0;
  let hi = ranges.length / 2 - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (cp < ranges[mid * 2]!) hi = mid - 1;
    else if (cp > ranges[mid * 2 + 1]!) lo = mid + 1;
    else return true;
  }
  return false;
}

/** Whether `font` has a glyph for every character of `text` (tabs and line breaks are ignored). */
export function fontCovers(font: PdfFontId, text: string): boolean {
  const ranges = FONT_COVERAGE[font];
  for (const ch of text) {
    const cp = ch.codePointAt(0)!;
    if (cp === 9 || cp === 10 || cp === 13) continue;
    if (!inRanges(ranges, cp)) return false;
  }
  return true;
}

/**
 * The font that draws all of `text` (after NFC normalization), or null when none does and the
 * page has to be a raster. Latin, Greek and Cyrillic get Noto Sans in the weight asked for; text
 * with CJK gets the CJK font, regular weight.
 */
export function unicodeFontFor(text: string, bold: boolean): PdfFontId | null {
  const t = text.normalize('NFC');
  if (fontCovers('sansRegular', t)) return bold ? 'sansBold' : 'sansRegular';
  if (fontCovers('cjk', t)) return 'cjk';
  return null;
}

/**
 * Whether `exportPdf` draws `text` as text: it is WinAnsi (the standard PDF fonts) or a bundled
 * font covers it (Latin, Greek, Cyrillic, CJK ideographs and kana). False means a page with this
 * text is embedded as an image (Arabic, Hebrew, Hangul, Indic scripts, emoji). Meant for a note
 * before exporting; the export itself checks every string it draws.
 *
 * @example
 * ```ts
 * pdfCanDrawText('пользователи'); // true
 * pdfCanDrawText('用户 ID'); // true
 * pdfCanDrawText('مستخدم'); // false: the page becomes an image
 * ```
 */
export function pdfCanDrawText(text: string): boolean {
  return isWinAnsi(text) || unicodeFontFor(text, false) !== null;
}

function base64ToBytes(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

async function inflate(bytes: Uint8Array): Promise<Uint8Array> {
  const stream = new ReadableStream<Uint8Array>({
    start(controller) {
      controller.enqueue(bytes);
      controller.close();
    },
  }).pipeThrough(new DecompressionStream('deflate') as unknown as TransformStream<Uint8Array>);
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

/**
 * The TrueType file of `font`. Lazy: the first call for a font loads its module (0.16 MB for
 * each Noto Sans weight, 2.1 MB for CJK, deflated and base64-encoded) and inflates it.
 */
export async function loadPdfFont(font: PdfFontId): Promise<Uint8Array> {
  const mod =
    font === 'sansRegular'
      ? await import('./fonts/sansRegular.js')
      : font === 'sansBold'
        ? await import('./fonts/sansBold.js')
        : await import('./fonts/cjk.js');
  return inflate(base64ToBytes(mod.data));
}

/** Bytes → the binary string jsPDF's virtual file system takes. */
export function bytesToBinaryString(bytes: Uint8Array): string {
  let out = '';
  const CHUNK = 0x8000;
  for (let i = 0; i < bytes.length; i += CHUNK) {
    out += String.fromCharCode(...bytes.subarray(i, i + CHUNK));
  }
  return out;
}
